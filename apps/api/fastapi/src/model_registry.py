# Schemas autogenerate compares: these, plus every schema a domain manifest
# declares. ``events`` is deliberately absent: its tables are hand-written SQL
# (2026-10-21_events_schema.py) and are not autogenerated.
TRACKED_SCHEMAS: set[str | None] = {
    None,
    "public",
    "hr",
    "cap",
    "org",
    "bookings",
    "stores",
    "billing",
    "environment",
    "almanac",
    "rewards",
    "flags",
    "payments",
    "platform",
} | tracked_schemas()

# Tables kept in the database with no model. ``userimage`` is the baseline
# migration's first user-image table, superseded by ``user_image`` (2026-09-20,
# ``src.auth.models.UserImage``); the owner asked to keep it untouched.
UNMODELLED_TABLES: frozenset[str] = frozenset({"userimage"})

# PostGIS installs its own tables (spatial_ref_sys, topology, the tiger
# geocoder). Their schemas are on the search path, so reflection lists them
# with the default schema; they belong to the extension, never to a migration.
_EXTENSION_TABLES = text(
    """
    SELECT c.relname
    FROM pg_class c
    JOIN pg_depend d ON d.objid = c.oid AND d.deptype = 'e'
    WHERE c.relkind IN ('r', 'p', 'v', 'm')
    """
)


def import_all_models() -> None:
    """Put every main-database table on ``Base.metadata``."""
    for module in LEGACY_MODEL_MODULES:
        import_module(module)
    import_models()


def extension_tables(connection: Connection) -> frozenset[str]:
    """Names of tables owned by a Postgres extension (PostGIS and friends)."""
    return frozenset(connection.execute(_EXTENSION_TABLES).scalars())


def object_filter(skip_tables: frozenset[str] = frozenset()) -> Any:
    """``include_object`` for Alembic: tracked schemas only, no extension tables.

    A reflected table with no model whose name an extension owns is skipped; a
    table the models define is always compared, whatever its name.
    """

    def include_object(
        object: Any, name: str | None, type_: str, reflected: bool, compare_to: Any
    ) -> bool:
        if type_ == "table":
            if getattr(object, "schema", None) not in TRACKED_SCHEMAS:
                return False
            if (
                reflected
                and compare_to is None
                and (name in skip_tables or name in UNMODELLED_TABLES)
            ):
                return False
        if type_ == "index" and reflected and compare_to is None:
            table = getattr(object, "table", None)
            if table is not None and (
                table.name in skip_tables or table.name in UNMODELLED_TABLES
            ):
                return False
        return True

    return include_object
