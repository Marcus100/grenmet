interface MarkProps {
  readonly alt: string;
  readonly className?: string;
}

function Mark({
  alt,
  className,
  paths,
  viewBox,
}: MarkProps & {
  readonly paths: readonly MarkPath[];
  readonly viewBox: string;
}) {
  return (
    <svg
      aria-label={alt}
      className={className}
      fill="currentColor"
      role="img"
      viewBox={viewBox}
      xmlns="http://www.w3.org/2000/svg"
    >
      <title>{alt}</title>
      {paths.map(({ d, rule }) => (
        <path d={d} fillRule={rule} key={d} />
      ))}
    </svg>
  );
}

