#!/usr/bin/env node
// Canonical legacy commands become discoverable skills for every agent client.
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const write = process.argv.includes("--write");
let drift = 0;
for (const filename of readdirSync(join(root, ".claude/commands"))) {
  if (!filename.endsWith(".md")) continue;
  const name = filename.slice(0, -3);
  const source = readFileSync(join(root, ".claude/commands", filename), "utf8");
  const sections = source.split(/^---\s*$/m);
  if (sections.length < 3)
    throw new Error(`Missing command frontmatter: ${filename}`);
  const description = sections[1].match(/^description:\s*(.+)$/m)?.[1];
  if (!description) throw new Error(`Missing command description: ${filename}`);
  const body = sections
    .slice(2)
    .join("---")
    .trim()
    .replace(/!`([^`]+)`/g, "`$1` (run to obtain current context)");
  const expected = `---\nname: ${name}\ndescription: ${description}\n---\n\n<!-- Generated by scripts/guardrails/sync-command-skills.mjs; edit .claude/commands/${filename}. -->\n\nUse this procedure when the user requests this task. Respect the current request's scope and existing authorization.\n\n${body}\n`;
  const target = join(root, ".claude/skills", name, "SKILL.md");
  if (existsSync(target) && readFileSync(target, "utf8") === expected) continue;
  if (
    existsSync(target) &&
    !readFileSync(target, "utf8").includes(
      "<!-- Generated by scripts/guardrails/sync-command-skills.mjs;"
    )
  ) {
    throw new Error(`Refusing to overwrite manually maintained skill: ${name}`);
  }
  drift++;
  if (write) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, expected);
    console.log(`UPDATED ${name}`);
  } else
    console.error(
      `DRIFT ${name}: run node scripts/guardrails/sync-command-skills.mjs --write`
    );
}
if (!drift) console.log("PASS portable command skills are synchronized");
process.exitCode = drift && !write ? 1 : 0;
