// Renders the API route index from the committed OpenAPI document. Pure
// functions only: no file or network I/O happens at import time. The CLI in
// generate-route-index.mjs does the reading and writing.

const METHODS = ["get", "post", "put", "patch", "delete", "head", "options"];
const METHOD_RANK = new Map(METHODS.map((method, rank) => [method, rank]));
const ZONES = new Set(["public", "me", "org", "admin"]);
const UNKNOWN = "—";

// Plain code-unit order, so the output does not depend on the locale.
function compareText(a, b) {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

function segments(path) {
  return path.split("/").filter(Boolean);
}

function isVersioned(parts) {
  return parts[0] === "api" && parts[1] === "v1";
}

// ADR-0025 audience zones. The usual place is /api/v1/<domain>/<zone>/..., but
// older routes carry the word elsewhere (/api/v1/admin/..., .../users/me/...),
// so the zone is the first literal public, me, org or admin segment after
// /api/v1. A {parameter} is never a zone. Paths outside /api/v1 are public.
function zoneOf(parts) {
  if (!isVersioned(parts)) return "public";
  return parts.slice(2).find((part) => ZONES.has(part)) ?? UNKNOWN;
}

// The owning domain: the segment after /api/v1/ (it matches src/<domain>), or
// after /api/ for unversioned paths. Tags split one domain into many labels.
function domainOf(parts) {
  let segment = parts[0];
  if (isVersioned(parts)) segment = parts[2];
  else if (parts[0] === "api") segment = parts[1];
  return segment ?? UNKNOWN;
}

// An operation without its own `security` key inherits the spec root. An
// explicit `security: []` on the operation means no authentication.
function authOf(operation, spec) {
  const security = "security" in operation ? operation.security : spec.security;
  return Array.isArray(security) && security.length > 0 ? "yes" : "no";
}

// Summaries are written by developers, but the file is rendered as Markdown:
// escape what could break a table cell, open a code span or start an HTML tag.
function summaryOf(operation) {
  const summary =
    typeof operation.summary === "string" ? operation.summary : "";
  return summary
    .replace(/\s*[\r\n]+\s*/gu, " ")
    .replace(/\\/gu, "\\\\")
    .replace(/[|`]/gu, "\\$&")
    .replace(/</gu, "&lt;")
    .replace(/>/gu, "&gt;")
    .trim();
}

// One record per operation, sorted by path and then by HTTP method.
export function collectOperations(spec) {
  const operations = [];
  for (const [path, item] of Object.entries(spec?.paths ?? {})) {
    if (item === null || typeof item !== "object") continue;
    const parts = segments(path);
    for (const key of Object.keys(item)) {
      if (!METHOD_RANK.has(key)) continue;
      const operation = item[key];
      if (operation === null || typeof operation !== "object") continue;
      operations.push({
        method: key.toUpperCase(),
        path,
        zone: zoneOf(parts),
        auth: authOf(operation, spec),
        summary: summaryOf(operation),
        operationId:
          typeof operation.operationId === "string"
            ? operation.operationId
            : "",
        domain: domainOf(parts),
      });
    }
  }
  return operations.sort(
    (a, b) =>
      compareText(a.path, b.path) ||
      METHOD_RANK.get(a.method.toLowerCase()) -
        METHOD_RANK.get(b.method.toLowerCase())
  );
}

function row(operation) {
  const id = operation.operationId ? `\`${operation.operationId}\`` : UNKNOWN;
  return `| ${operation.method} | \`${operation.path}\` | ${operation.zone} | ${operation.auth} | ${operation.summary} | ${id} |`;
}

export function renderRouteIndex(spec) {
  const operations = collectOperations(spec);
  const pathCount = new Set(operations.map((operation) => operation.path)).size;
  const domains = [
    ...new Set(operations.map((operation) => operation.domain)),
  ].sort(compareText);

  const lines = [
    "# API route index",
    "",
    "**Status:** Generated reference  ",
    "**Owner:** Barrels Grenada engineering  ",
    "**Last updated:** generated from `apps/api/fastapi/openapi.json`; do not edit by hand",
    "",
    "This file is generated by `pnpm generate:api-routes` and lists every operation in the API. Behaviour and policy live in `docs/api/contracts.md`.",
    "",
    `Totals: ${pathCount} paths and ${operations.length} operations.`,
  ];

  for (const domain of domains) {
    lines.push(
      "",
      `## ${domain}`,
      "",
      "| Method | Path | Zone | Auth | Summary | Operation ID |",
      "| --- | --- | --- | --- | --- | --- |"
    );
    for (const operation of operations) {
      if (operation.domain === domain) lines.push(row(operation));
    }
  }
  return `${lines.join("\n")}\n`;
}
