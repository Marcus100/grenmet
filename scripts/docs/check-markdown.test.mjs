import assert from "node:assert/strict";
import test from "node:test";
import {
  checkMarkdown,
  checkRepository,
  checkSkillFrontmatter,
} from "./check-markdown.mjs";

const rules = (text, options) =>
  checkMarkdown(text, options).map((violation) => violation.rule);

test("a fence without a language is flagged; labelled fences pass", () => {
  assert.deepEqual(rules("# T\n\n```\nplain\n```\n"), ["fence-language"]);
  assert.deepEqual(rules("# T\n\n```text\nplain\n```\n"), []);
  assert.deepEqual(rules("# T\n\n~~~bash\nls\n~~~\n"), []);
});

test("closing fences and nested longer fences are not mistaken for openings", () => {
  const nested = "# T\n\n````markdown\n```\ninner\n```\n````\n";
  assert.deepEqual(rules(nested), []);
});

test("comment lines inside code are not headings", () => {
  assert.deepEqual(rules("# T\n\n```bash\n# not a heading\nls\n```\n"), []);
});

test("a second H1 and skipped heading levels are flagged", () => {
  assert.deepEqual(rules("# A\n\n# B\n"), ["single-h1"]);
  assert.deepEqual(rules("# A\n\n### C\n"), ["heading-skip"]);
  assert.deepEqual(rules("# A\n\n## B\n\n### C\n\n## D\n"), []);
});

test("the block regenerated by next dev is exempt", () => {
  const text =
    "# App\n\n<!-- BEGIN:nextjs-agent-rules -->\n\n# This is NOT the Next.js you know\n\n<!-- END:nextjs-agent-rules -->\n";
  assert.deepEqual(rules(text), []);
});

test("locked upstream skills can skip the fence rule", () => {
  assert.deepEqual(rules("# T\n\n```\nx\n```\n", { skipFences: true }), []);
});

test("skill frontmatter needs a name matching its folder and a description", () => {
  const good = "---\nname: tdd\ndescription: Test-driven development.\n---\n";
  assert.deepEqual(checkSkillFrontmatter(good, "tdd"), []);
  assert.deepEqual(
    checkSkillFrontmatter(good, "other").map((v) => v.rule),
    ["skill-name"]
  );
  assert.deepEqual(
    checkSkillFrontmatter("---\nname: tdd\n---\n", "tdd").map((v) => v.rule),
    ["skill-description"]
  );
  assert.equal(checkSkillFrontmatter("# no frontmatter", "tdd").length, 2);
});

test("every tracked Markdown file in the repository follows the conventions", () => {
  const { checked, results } = checkRepository();
  assert.ok(checked > 200, `expected to check the repo, saw ${checked} files`);
  assert.deepEqual(
    results.map((r) => `${r.file}:${r.line} [${r.rule}] ${r.message}`),
    []
  );
});
